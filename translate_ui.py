def english_ui(template: str) -> str:
    for old, new in REPLACEMENTS:
        if old not in template:
            raise ValueError(f'UI translation anchor missing: {old[:100]}')
        template = template.replace(old, new)
    # Remove Chinese-only source comments from the generated English artifact, not the source template.
    template = re.sub(r'^\s*/\*[^\n]*[\u3400-\u9fff][^\n]*\*/\s*$', '', template, flags=re.M)
    remaining = [(i, line[:200]) for i,line in enumerate(template.splitlines(),1)
                 if re.search(r'[\u3400-\u9fff]',line)]
    if remaining: raise ValueError(f'Untranslated UI text: {remaining[:12]}')
    return template
